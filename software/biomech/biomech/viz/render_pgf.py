"""Render specs to TikZ/pgfplots figures and booktabs/siunitx tables (an08 §4).

Output layout (``out_dir`` is the paper's directory or any export folder)::

    <out_dir>/jtsmm-pgfstyle.tex          colours, roles, ramps, axis defaults (\\input once)
    <out_dir>/figures/<id>/fig.tex       \\input{figures/<id>/fig.tex} inside a figure env
    <out_dir>/figures/<id>/*.dat|*.png   plot data (LTTB / RDP thinned, 'nan' = break), images
    <out_dir>/tables/<id>.tex            the table body; caption/label stay in the paper

Geometry comes from :func:`biomech.viz.layout.compute`: every axis is placed at
absolute coordinates (inches) with ``scale only axis``, its ticks and tick
labels are explicit, and legends are nodes *below* the axis' label band, so
nothing can overlap the data or a neighbour.

Preamble needs: ``\\usepackage{pgfplots}\\pgfplotsset{compat=1.18}
\\usepackage{booktabs,siunitx,array,tabularx}\\input{jtsmm-pgfstyle}`` (sans venues under
LuaLaTeX: define ``\\jtsmmunicodesym`` and give the sans font a fallback with Greek/math
glyphs to typeset ω, ≤, ... in the sans face; see ``style._SANS_UPLOAD``).
Data paths are written relative to ``data_root`` (default: ``out_dir``), which
must be LaTeX's working directory when compiling.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

import numpy as np

from biomech.viz import layout as L
from biomech.viz import style
from biomech.viz.downsample import lttb, rdp
from biomech.viz.spec import Column, FigureSpec, Series, TableSpec

MAX_POINTS = 1500
RDP_TOL_MM = 0.05
_DASH = {"solid": "solid", "dashed": "dash pattern=on 3pt off 2pt", "dotted":
         "dash pattern=on 0.8pt off 1.4pt"}
_MARK = {"o": "*", "s": "square*", "^": "triangle*", "d": "diamond*", "v": "triangle*",
         "x": "x", "|": "|", "oo": "o", "none": "*"}     # "oo": open circle (e.g. a null)
# Marker shapes that need a rotation to differ from another ('v' is a '^' turned over).
_MARK_ROT = {"v": 180}
# Absolute font sizes per venue (D1): macros defined by write_style, so a figure never drifts
# with the document class size (\footnotesize is 8 pt only in a 10-pt document).
_FONT_CMD = {k: f"\\jtsmmfont{k}" for k in ("label", "title", "tick", "legend", "note", "tag")}


# Stroke-only marks: the role mark styles outline filled marks in white (a halo on dense
# scatter), which would erase a cross or tick entirely (the condyle-midpoint cross
# was invisible); their outline is drawn in the series colour instead.
_STROKE_MARKS = ("x", "|", "oo")


def _mark(m: str) -> str:
    """pgfplots mark options of marker code ``m`` (``mark=...`` plus a rotation if needed)."""
    out = f"mark={_MARK.get(m, '*')}"
    if m in _STROKE_MARKS:
        out += ", mark options={solid, line width=0.8pt}"
    if m in _MARK_ROT:
        out += f", every mark/.append style={{rotate={_MARK_ROT[m]}}}"
    return out


def _font_macro(pt: float, family: str, bold: bool = False) -> str:
    f = f"\\fontsize{{{pt:g}}}{{{1.2 * pt:.4g}}}\\selectfont"
    if family == "sans":
        f += "\\sffamily"
    if bold:
        f += "\\bfseries"
    return f


def _role_key(r: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "", r)


def write_style(out_dir: Path, venue: str | style.Venue | None = None) -> Path:
    """``jtsmm-pgfstyle.tex`` for ``venue`` (default: the active one): colours, ramps, roles,
    and the venue's absolute figure fonts (``\\jtsmmfont<label|tick|title|legend|note|tag>``),
    the figure minus sign ``\\jtsmmminus`` and ``\\jtsmmfigsetup`` (figure font family; units
    typeset in the surrounding text font)."""
    V = style.venue(venue)
    lines = ["% Generated by biomech.viz.render_pgf -- do not edit.",
             f"% Venue: {V.name} (column {V.column_in:.3f} in, text {V.text_in:.3f} in,"
             f" figure font: {V.family})",
             "\\pgfplotsset{compat=1.18}"]
    for k in _FONT_CMD:
        f = _font_macro(V.font_pt.get(k, 8.0), V.family, k == "tag")
        lines.append(f"\\def\\jtsmmfont{k}{{{f}}}")
    # U+2212 in figure text and table cells: the text font's own minus (\textminus), so the
    # sign matches the digits and one font family is used (in math: the math minus).
    lines.append("\\def\\jtsmmminus{\\ifmmode-\\else\\textminus\\fi}")
    # Math symbols in figure text (≤ ≥ ≈ ≠ and Greek): in sans venues the Unicode glyph of
    # the sans figure font (with the DejaVu fallback of the upload preamble), else the
    # document's math (E32). Symbols that have a text glyph use it (see _UNICODE).
    if V.family == "sans":
        lines.append("\\def\\jtsmmsym#1#2{\\ifdefined\\jtsmmunicodesym#1\\else"
                     "\\ensuremath{#2}\\fi}")
    else:
        lines.append("\\def\\jtsmmsym#1#2{\\ensuremath{#2}}")
    # per-mode=symbol: "°/s", "/min" as in the previews; a "s⁻¹" superscript would drop to
    # the math script size (6 pt at 8-pt lettering), below the Springer minimum of 7 pt.
    lines.append("\\def\\jtsmmfigsetup{" + ("\\sffamily" if V.family == "sans" else "")
                 + "\\ifdefined\\sisetup\\sisetup{mode=match, reset-text-family=false,"
                 " reset-text-series=false, reset-text-shape=false, per-mode=symbol}\\fi}")
    # Superscripts (the 2 of °/s²) at the venue's minimum size, not the 6-pt script size of
    # 8-pt lettering: a text superscript macro, and math script sizes for the figure sizes
    # (siunitx \squared). \DeclareMathSizes works in the preamble only, where the exports
    # \input this file.
    mn = max(V.min_pt, 1.0)
    lines.append(f"\\def\\jtsmmsup#1{{\\raisebox{{0.6ex}}{{\\fontsize{{{mn:g}}}{{{mn:g}}}"
                 "\\selectfont #1}}")
    for sz in sorted({float(v) for v in V.font_pt.values()}):
        lines.append(f"\\DeclareMathSizes{{{sz:g}}}{{{sz:g}}}{{{max(mn, sz * 0.7):g}}}"
                     f"{{{mn:g}}}")
    # units siunitx does not define (style.UNITS maps them to their text for previews)
    lines.append("\\ifdefined\\DeclareSIUnit\\DeclareSIUnit\\pixel{px}\\fi")
    lines.append("\\ifdefined\\DeclareSIUnit\\DeclareSIUnit\\ppm{ppm}\\fi")
    for name, hx in style.PALETTE.items():
        lines.append(f"\\definecolor{{jt{name}}}{{HTML}}{{{hx}}}")
    for name, hx in style.THEMES["light"].items():
        lines.append(f"\\definecolor{{jt{name}}}{{HTML}}{{{hx}}}")

    def cmap(name: str, vals: tuple[str, ...]) -> str:
        stops = " ".join(f"rgb255({i}cm)=({int(v[0:2], 16)},{int(v[2:4], 16)},{int(v[4:6], 16)})"
                         for i, v in enumerate(vals))
        return f"\\pgfplotsset{{colormap={{{name}}}{{{stops}}}}}"

    lines.append(cmap("jtseq", style.SEQUENTIAL))
    lines.append(cmap("jtdiv", style.DIVERGING))
    lines.append("\\pgfplotsset{")
    lines.append(
        "  jtsmm/base/.style={scale only axis, enlargelimits=false, clip mode=individual,"
        f" label style={{font={_FONT_CMD['label']}, text=jtink, inner sep=1pt}},"
        f" tick label style={{font={_FONT_CMD['tick']}, text=jtink2, inner sep=1pt}},"
        f" title style={{font={_FONT_CMD['title']}, text=jtink, at={{(0,1)}},"
        " anchor=south west, inner xsep=0pt, inner ysep=2pt},"
        f" legend style={{font={_FONT_CMD['legend']}, draw=none, fill=none, text=jtink,"
        " inner sep=0pt, row sep=0pt, nodes={inner ysep=1pt, inner xsep=1.5pt},"
        " legend cell align=left, /tikz/every even column/.append style={column sep=6pt}},"
        " grid=major, major grid style={jtgrid, line width=0.45pt},"
        " axis x line*=bottom, axis y line*=left, axis line style={jtaxis, line width=0.45pt},"
        " tick style={jtaxis, line width=0.45pt}, major tick length=2.5pt, minor tick num=0,"
        " unbounded coords=jump, scaled ticks=false,"
        f" every axis plot/.append style={{line width={style.LINE_PT}pt}}}},")
    lines.append("  jtsmm/base3d/.style={scale only axis, enlargelimits=false, grid=major,"
                 " major grid style={jtgrid, line width=0.4pt},"
                 f" label style={{font={_FONT_CMD['note']}, text=jtink2}},"
                 f" tick label style={{font={_FONT_CMD['note']}, text=jtink2}},"
                 f" title style={{font={_FONT_CMD['title']}, text=jtink, at={{(0,1)}},"
                 " anchor=south west, inner xsep=0pt},"
                 " axis line style={jtaxis, line width=0.4pt}, unbounded coords=jump,"
                 # 3-D legends go below the axis like the 2-D ones (no frame, same font).
                 f" legend style={{font={_FONT_CMD['legend']}, draw=none, fill=none, text=jtink,"
                 " legend cell align=left,"
                 " /tikz/every even column/.append style={column sep=6pt}}},")
    lines.append("}")
    # Roles are defined in both key trees: /pgfplots for \\addplot options and
    # /tikz for plain \\draw / \\fill (reference lines, shaded spans).
    for setter in ("\\pgfplotsset", "\\tikzset"):
        lines.append(setter + "{")
        for r, (col, dash, mark) in style.ROLES.items():
            # Lines carry no mark (their legend sample stays a plain line); marker series
            # add jtsmm/mark/<role>.
            lines.append(f"  jtsmm/role/{_role_key(r)}/.style={{color=jt{col}, {_DASH[dash]}}},")
            rot = f", rotate={_MARK_ROT[mark]}" if mark in _MARK_ROT else ""
            outline = ("line width=0.8pt" if mark in _STROKE_MARKS
                       else "draw=white, line width=0.3pt")
            lines.append(f"  jtsmm/mark/{_role_key(r)}/.style={{mark={_MARK.get(mark, '*')},"
                         f" mark size={V.marker_pt:.2f}pt,"
                         f" mark options={{solid, {outline}{rot}}}}},")
        lines.append("}")
    p = Path(out_dir) / "jtsmm-pgfstyle.tex"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return p


# Superscript note letters a-z (no q in Unicode) for table notes (compact tables, 2026-11-05).
SUP_LETTERS = "ᵃᵇᶜᵈᵉᶠᵍʰⁱʲᵏˡᵐⁿᵒᵖʳˢᵗᵘᵛʷˣʸᶻ"

# Text glyphs follow the figure font (sans in Springer / Nature figures); the others go
# through \jtsmmsym (the Unicode glyph in sans venues, math otherwise).
_UNICODE = {"≥": "\\jtsmmsym{≥}{\\geq}", "≤": "\\jtsmmsym{≤}{\\leq}", "±": "\\textpm{}",
            "°": "\\textdegree{}", "−": "{\\jtsmmminus}", "×": "\\texttimes{}", "–": "--",
            "µ": "\\textmu{}", "θ": "\\jtsmmsym{θ}{\\theta}", "ω": "\\jtsmmsym{ω}{\\omega}",
            "α": "\\jtsmmsym{α}{\\alpha}", "²": "\\jtsmmsup{2}",
            "→": "\\textrightarrow{}", "Δ": "\\jtsmmsym{Δ}{\\Delta}", "σ": "\\jtsmmsym{σ}{\\sigma}",
            "≠": "\\jtsmmsym{≠}{\\neq}", "≈": "\\jtsmmsym{≈}{\\approx}",
            "ρ": "\\jtsmmsym{ρ}{\\rho}", "δ": "\\jtsmmsym{δ}{\\delta}",
            "κ": "\\jtsmmsym{κ}{\\kappa}", "Ω": "\\jtsmmsym{Ω}{\\Omega}",
            "√": "\\jtsmmsym{√}{\\surd}", "′": "\\jtsmmsym{′}{{}^{\\prime}}",
            "ⁿ": "\\jtsmmsup{n}", "³": "\\jtsmmsup{3}", "⁴": "\\jtsmmsup{4}",
            "⁵": "\\jtsmmsup{5}", "⁶": "\\jtsmmsup{6}",
            **{u: f"\\jtsmmsup{{{c}}}" for u, c in zip(SUP_LETTERS, "abcdefghijklmnoprstuvwxyz")
               if c != "n"},
            # check / cross marks: base-LaTeX math stand-ins in a paper's own preamble
            "✓": "\\jtsmmsym{✓}{\\ifdefined\\checkmark\\checkmark\\else\\surd\\fi}",
            "✗": "\\jtsmmsym{✗}{\\times}",
            "\u00a0": "~"}


_GREEK_SUB = re.compile(r"([σδρκθωαΔ])_([A-Za-z0-9]+)")


def _esc(s: str) -> str:
    """Escape text for LaTeX; ``$...$`` math segments are passed through untouched. Sign
    hyphens become U+2212 (:func:`style.unicode_minus`) and then ``\\jtsmmminus``."""
    parts = re.split(r"(\$[^$]*\$)", s)
    out = []
    for part in parts:
        if part.startswith("$") and part.endswith("$") and len(part) >= 2:
            out.append(part)
            continue
        # A Greek symbol with a word subscript written plainly (σ_obs, σ_JTS, δ_t): a real
        # subscript, not a literal underscore.
        part = _GREEK_SUB.sub(lambda m: f"{m.group(1)}\x00{m.group(2)}\x01", part)
        t = (style.unicode_minus(part).replace("\\", "\\textbackslash{}").replace("%", "\\%").replace("&", "\\&")
             .replace("#", "\\#").replace("_", "\\_"))
        for u, tex in _UNICODE.items():
            t = t.replace(u, tex)
        t = re.sub("\x00([A-Za-z0-9]+)\x01", r"\\textsubscript{\1}", t)
        # Bare < and > render as inverted punctuation in text mode.
        t = re.sub(r"([<>])", r"$\1$", t)
        out.append(t)
    return "".join(out)


def _axis_label(label: str, unit: str) -> str:
    if not label:
        return ""
    return f"{_esc(label)} (\\si{{{unit}}})" if unit else _esc(label)


def _fmt(v: float) -> str:
    return "nan" if not np.isfinite(v) else f"{v:.6g}"


def _write_dat(path: Path, cols: dict[str, np.ndarray]) -> None:
    keys = list(cols)
    arr = np.column_stack([np.asarray(cols[k], float).ravel() for k in keys]) if keys else []
    rows = [" ".join(keys)] + [" ".join(_fmt(v) for v in r) for r in arr]
    path.write_text("\n".join(rows) + "\n", encoding="utf-8")


def _meta_lim(lim: tuple[float, float] | None, z: np.ndarray, *, diverging: bool = False
              ) -> tuple[float, float]:
    """Colour range of a heatmap: the given limits, else the data range (symmetric about 0
    for a diverging ramp); never degenerate (pgfplots aborts when min == max)."""
    if lim is None:
        fin = np.asarray(z, float)[np.isfinite(z)]
        lo, hi = (float(fin.min()), float(fin.max())) if fin.size else (0.0, 1.0)
        if diverging:
            m = max(abs(lo), abs(hi))
            lo, hi = -m, m
    else:
        lo, hi = float(lim[0]), float(lim[1])
    if not hi > lo:
        pad = max(abs(lo) * 0.05, 1e-6)
        lo, hi = lo - pad, hi + pad
    return lo, hi


def _thin(x: np.ndarray, y: np.ndarray) -> np.ndarray:
    """Indices kept for the pgf data file: LTTB per finite run (budget by run length),
    every run's first and last point and one NaN between runs, so gaps stay gaps and no
    triangle ever spans two runs."""
    if len(x) <= MAX_POINTS:
        return np.arange(len(x))
    ok = np.isfinite(x) & np.isfinite(y)
    if ok.all():
        return lttb(x, y, MAX_POINTS)
    edges = np.flatnonzero(np.diff(np.r_[0, ok.astype(np.int8), 0]))
    runs = list(zip(edges[::2], edges[1::2]))
    total = max(int(ok.sum()), 1)
    keep = [np.flatnonzero(~ok)]
    for a, b in runs:
        n = b - a
        budget = max(3, int(round(MAX_POINTS * n / total)))
        keep.append(a + lttb(x[a:b], y[a:b], budget))
    return np.unique(np.concatenate(keep))


def _col(s: Series) -> str:
    """``, color=jt<name>`` for a per-series colour override of a reference line (else "")."""
    return f", color=jt{s.style['color']}" if "color" in s.style else ""


def _opts(s: Series, extra: str = "") -> str:
    o = [f"jtsmm/role/{_role_key(s.role)}"]
    if extra:                                # mode/mark styles first, per-series tweaks after
        o.append(extra)
    w = float(s.style.get("width", 1.0))
    if s.role in ("context", "muted", "faint"):
        o.append(f"line width={style.THIN_PT * w:.2f}pt")
    elif w != 1.0:
        o.append(f"line width={style.LINE_PT * w:.2f}pt")
    mf = style.marker_factor(s) if s.kind == "scatter" else float(s.style.get("size", 1.0))
    if "size" in s.style or mf != 1.0:
        o.append(f"mark size={style.marker_pt() * mf:.2f}pt")
    halo = style.halo_pt(s) if s.kind == "scatter" else None
    if halo is not None and halo != 0.3:
        # a wider surface-coloured outline: lifts a marker off the line it ends, a reference
        # line under it and neighbouring dots (pt; the role default is 0.3 pt)
        o.append(f"every mark/.append style={{draw=white, line width={halo:.2f}pt}}")
    if "alpha" in s.style and s.kind not in ("fill", "band"):
        o.append(f"opacity={float(s.style['alpha']):.2f}")
    # Per-series overrides of the role (style.resolve): after the role style, so they win.
    if "color" in s.style:
        o.append(f"color=jt{s.style['color']}")
    if "dash" in s.style and s.kind not in ("scatter", "errorbar"):
        o.append(_DASH.get(str(s.style["dash"]), "solid"))
    if not s.label:
        o.append("forget plot")             # unlabelled plots must not take legend slots
    elif s.kind in ("band", "fill", "bar", "barh"):
        o.append("area legend")
    return ", ".join(o)


def _series_tex(s: Series, pl: L.PanelLayout, pi: int, si: int, out: Path, rel: str
                ) -> tuple[list[str], bool]:
    """TeX lines of one series and whether it produced a legend entry."""
    name = f"p{pi}s{si}.dat"
    lines: list[str] = []
    k = s.kind
    legend = bool(s.label)
    x0, x1 = pl.x.lim
    y0, y1 = pl.y.lim
    if k in ("line", "scatter") and s.label and not (
            np.isfinite(np.asarray(s.x, float)) & np.isfinite(np.asarray(s.y, float))).any():
        # A legend-only entry (no finite point, e.g. the key of a reference line): pgfplots
        # cannot draw a legend image from a plot without coordinates.
        mode = "no markers" if k == "line" else f"only marks, jtsmm/mark/{_role_key(s.role)}"
        if k == "scatter" and "ms" in s.style:     # the per-series marker, as for real points
            mode += ", " + _mark(s.style["ms"])
        lines.append(f"\\addlegendimage{{{_opts(s, mode)}}}")
        lines.append(f"\\addlegendentry{{{_esc(s.label)}}}")
        return lines, True
    if k in ("line", "scatter"):
        x, y = np.asarray(s.x, float), np.asarray(s.y, float)
        idx = _thin(x, y) if k == "line" else np.arange(len(x))
        cols = {"x": x[idx], "y": y[idx]}
        meta = ""
        if k == "scatter" and s.c is not None:
            cols["c"] = np.asarray(s.c, float)[idx]
            cbp = pl.panel.colorbar
            meta = (", scatter, point meta=explicit, colormap name="
                    + ("jtdiv" if cbp and cbp.ramp == "diverging" else "jtseq"))
        _write_dat(out / name, cols)
        mode = "no markers" if k == "line" else f"only marks, jtsmm/mark/{_role_key(s.role)}"
        if k == "scatter" and "ms" in s.style:
            mode += ", " + _mark(s.style["ms"])
        tbl = "table[x=x, y=y" + (", meta=c]" if meta else "]")
        lines.append(f"\\addplot[{_opts(s, mode + meta)}] {tbl} {{{rel}/{name}}};")
    elif k == "band":
        # One closed fill per finite run: a band never bridges a gap (masked samples,
        # cycles without data), as in the viewer (render_plotly._runs).
        x = np.asarray(s.x, float)
        lo, hi = np.asarray(s.y, float), np.asarray(s.y2, float)
        ok = np.isfinite(lo) & np.isfinite(hi) & np.isfinite(x)
        edges = np.flatnonzero(np.diff(np.r_[0, ok.astype(np.int8), 0]))
        a = style.BAND_ALPHA * float(s.style.get("alpha", 1.0))
        for j, (r0, r1) in enumerate(zip(edges[::2], edges[1::2])):
            nm = name if j == 0 else f"p{pi}s{si}r{j}.dat"
            xr, lr, hr = x[r0:r1], lo[r0:r1], hi[r0:r1]
            _write_dat(out / nm, {"x": np.r_[xr, xr[::-1]], "y": np.r_[lr, hr[::-1]]})
            opts = _opts(s) if j == 0 else _opts(s).replace(", area legend", "") + \
                ", forget plot"
            if j and "forget plot, forget plot" in opts:
                opts = opts.replace("forget plot, forget plot", "forget plot")
            lines.append(f"\\addplot[{opts}, no markers, draw=none, fill,"
                         f" fill opacity={a:.2f}] table[x=x, y=y] {{{rel}/{nm}}} -- cycle;")
            if j == 0 and s.label:
                # The legend entry belongs right after the first fill; later runs are
                # "forget plot" and take no slot.
                lines.append(f"\\addlegendentry{{{_esc(s.label)}}}")
        legend = False if not s.label else "added"
    elif k == "fill":
        _write_dat(out / name, {"x": np.asarray(s.x, float), "y": np.asarray(s.y, float)})
        a = float(s.style.get("alpha", style.BAND_ALPHA))
        lines.append(f"\\addplot[{_opts(s)}, no markers, fill, fill opacity={a:.2f},"
                     f" line width={style.THIN_PT}pt] table[x=x, y=y] {{{rel}/{name}}} -- cycle;")
    elif k == "errorbar":
        x, y = np.asarray(s.x, float), np.asarray(s.y, float)
        _write_dat(out / name, {"x": x, "y": y, "ep": np.asarray(s.y2, float) - y,
                                "em": y - np.asarray(s.ylo, float)})
        # a per-series marker (the participant shape) wins over the role's, as in the
        # scatter branch and in matplotlib
        mk = s.style.get("ms") or s.style.get("marker")
        lines.append(f"\\addplot[{_opts(s)}, only marks, jtsmm/mark/{_role_key(s.role)}"
                     + (f", {_mark(mk)}" if mk else "") + ","
                     f" error bars/.cd, y dir=both, y explicit,"
                     f" error bar style={{line width={style.LINE_PT}pt}}, error mark=none]"
                     f" table[x=x, y=y, y error plus=ep, y error minus=em] {{{rel}/{name}}};")
    elif k in ("bar", "barh"):
        x, y = np.asarray(s.x, float), np.asarray(s.y, float)
        _write_dat(out / name, {"x": x, "y": y})
        bw = float(s.style.get("bar_width", 0.62))
        unit = pl.axis.w / (x1 - x0) if k == "bar" else pl.axis.h / (y1 - y0)
        kind = "ybar" if k == "bar" else "xbar"
        lines.append(f"\\addplot[{_opts(s)}, {kind}, bar width={bw * unit:.3f}in, fill,"
                     f" draw=none, mark=none, bar shift=0pt] table[x=x, y=y] {{{rel}/{name}}};")
    elif k == "hline":
        for i, v in enumerate(np.atleast_1d(s.y)):
            lines.append(f"\\draw[jtsmm/role/{_role_key(s.role)}, line width=0.6pt{_col(s)}]"
                         f" (axis cs:{_fmt(x0)},{_fmt(v)}) -- (axis cs:{_fmt(x1)},{_fmt(v)});")
            t = s.text[i] if s.text and i < len(s.text) else (s.label if i == 0 else None)
            if t:
                left = s.style.get("anchor") == "left"     # label at the left end of the line
                lines.append(f"\\node[anchor=south {'west' if left else 'east'}, inner sep=1pt,"
                             f" font={_FONT_CMD['note']}, text=jtink2] at (axis cs:"
                             f"{_fmt(x0 if left else x1)},{_fmt(v)}) {{{_esc(t)}}};")
        legend = False
    elif k == "vline":
        for i, v in enumerate(np.atleast_1d(s.x)):
            if not min(x0, x1) <= float(v) <= max(x0, x1):   # not clipped either (see hspan)
                continue
            lines.append(f"\\draw[jtsmm/role/{_role_key(s.role)}, line width=0.6pt{_col(s)}]"
                         f" (axis cs:{_fmt(v)},{_fmt(y0)}) -- (axis cs:{_fmt(v)},{_fmt(y1)});")
            t = s.text[i] if s.text and i < len(s.text) else (s.label if i == 0 else None)
            if t:
                rev = pl.panel.y.reverse or any(q.kind == "heatmap" for q in pl.panel.series)
                lines.append(f"\\node[anchor=north west, inner sep=1pt, font={_FONT_CMD['note']},"
                             f" text=jtink2] at (axis cs:{_fmt(v)},{_fmt(y0 if rev else y1)})"
                             f" {{{_esc(t)}}};")
        legend = False
    elif k == "hspan":
        for a, b in zip(np.atleast_1d(s.x), np.atleast_1d(s.y2)):
            # TikZ fills are not clipped by the axis: a span outside a cropped x range
            # would stretch the figure (a 16-in time series)
            a, b = max(float(a), min(x0, x1)), min(float(b), max(x0, x1))
            if not b > a:
                continue
            op = _fmt(float(s.style.get("alpha", 0.12)))
            lines.append(f"\\fill[jtsmm/role/{_role_key(s.role)}, opacity={op}, draw=none]"
                         f" (axis cs:{_fmt(a)},{_fmt(y0)}) rectangle (axis cs:{_fmt(b)},{_fmt(y1)});")
        legend = False
    elif k == "sigbar":
        yy = L.sigbar_y(int(s.style.get("row", 0)))
        col = "jtink2" if s.role in ("context", "muted", "faint") else \
            f"jt{style.role(s.role)[0]}"
        for a, b in zip(np.atleast_1d(s.x), np.atleast_1d(s.y2)):
            lines.append(f"\\draw[{col}, line width=2.4pt] ({{axis cs:{_fmt(a)},0}}|-"
                         f"{{rel axis cs:0,{yy:.4f}}}) -- ({{axis cs:{_fmt(b)},0}}|-"
                         f"{{rel axis cs:0,{yy:.4f}}});")
        if s.label:
            lines.append(f"\\addlegendimage{{{col}, line width=2.4pt}}")
            lines.append(f"\\addlegendentry{{{_esc(s.label)}}}")
        legend = False
    elif k == "heatmap":
        z = np.asarray(s.z, float)
        ny, nx = z.shape
        X, Y = np.meshgrid(np.arange(nx), np.arange(ny))
        _write_dat(out / name, {"x": X.ravel(), "y": Y.ravel(), "c": z.ravel()})
        cb = pl.panel.colorbar
        lim = _meta_lim(cb.lim if cb and cb.lim else None, z,
                        diverging=bool(cb and cb.ramp == "diverging"))
        cmap = "jtdiv" if cb and cb.ramp == "diverging" else "jtseq"
        lines.append(f"\\addplot[matrix plot*, mesh/cols={nx}, mesh/rows={ny}, point meta=explicit,"
                     f" colormap name={cmap}, point meta min={_fmt(lim[0])},"
                     f" point meta max={_fmt(lim[1])}] table[x=x, y=y, meta=c] {{{rel}/{name}}};")
        if s.text:
            span = (lim[1] - lim[0]) or 1.0
            for (yy, xx), t in zip(np.ndindex(ny, nx), s.text):
                dark = np.isfinite(z[yy, xx]) and (z[yy, xx] - lim[0]) / span > 0.6
                lines.append(f"\\node[font={_FONT_CMD['note']}, text={'white' if dark else 'jtink'}]"
                             f" at (axis cs:{xx},{yy}) {{{_esc(t)}}};")
        legend = False
    elif k == "text":
        anchor = {"right": "west", "left": "east", "above": "south", "below": "north"}[
            s.style.get("anchor", "right")]
        color = s.style.get("color", "ink2")
        for xx, yy, t in zip(np.atleast_1d(s.x), np.atleast_1d(s.y), s.text or []):
            lines.append(f"\\node[font={_FONT_CMD['note']}, anchor={anchor}, inner sep=1.5pt,"
                         f" text=jt{color}] at (axis cs:{_fmt(xx)},{_fmt(yy)}) {{{_esc(t)}}};")
        legend = False
    elif k == "colorline":
        P = np.column_stack([s.x, s.y]).astype(float)
        idx = rdp(P, RDP_TOL_MM) if len(P) > MAX_POINTS else np.arange(len(P))
        _write_dat(out / name, {"x": P[idx, 0], "y": P[idx, 1],
                                "c": np.asarray(s.c, float)[idx]})
        cb = pl.panel.colorbar
        lim = _meta_lim(cb.lim if cb and cb.lim else s.style.get("lim"), np.asarray(s.c, float),
                        diverging=bool(cb and cb.ramp == "diverging"))
        cmap = "jtdiv" if cb and cb.ramp == "diverging" else "jtseq"
        lw = style.LINE_PT * 1.3 * float(s.style.get("width", 1.0))
        lines.append(f"\\addplot[mesh, point meta=explicit, colormap name={cmap}, no markers,"
                     f" line width={lw:.2f}pt, point meta min={_fmt(lim[0])},"
                     f" point meta max={_fmt(lim[1])}] table[x=x, y=y, meta=c] {{{rel}/{name}}};")
    elif k == "arrow":
        d = np.asarray(s.d, float).reshape(-1, 2)
        _write_dat(out / name, {"x": np.atleast_1d(s.x), "y": np.atleast_1d(s.y), "u": d[:, 0],
                                "v": d[:, 1]})
        lines.append(f"\\addplot[{_opts(s)}, -stealth, no markers, quiver={{u=\\thisrow{{u}},"
                     f" v=\\thisrow{{v}}}}] table[x=x, y=y] {{{rel}/{name}}};")
    elif k == "image":
        from matplotlib.image import imsave

        png = f"p{pi}s{si}.png"
        if np.ndim(s.img) == 2 and s.style.get("cmap"):
            from biomech.viz.render_mpl import scalar_rgba

            # Colour-mapped map: NaN transparent; pixels repeated so PDF viewers' image
            # smoothing keeps the cells crisp.
            rgba = scalar_rgba(s, "light")
            rep_ = max(1, int(np.ceil(400 / max(rgba.shape[:2]))))
            imsave(out / png, np.repeat(np.repeat(rgba, rep_, 0), rep_, 1))
        else:
            imsave(out / png, s.img, cmap="gray" if np.ndim(s.img) == 2 else None)
        ex = s.extent or (0, s.img.shape[1], s.img.shape[0], 0)
        # "forget plot": a graphics plot otherwise takes a legend slot and shifts every later
        # entry's image by one (emg_onset_raster, emg_cycle_spectrogram).
        lines.append(f"\\addplot[forget plot] graphics[xmin={_fmt(ex[0])}, xmax={_fmt(ex[1])},"
                     f" ymin={_fmt(min(ex[2], ex[3]))}, ymax={_fmt(max(ex[2], ex[3]))}]"
                     f" {{{rel}/{png}}};")
        legend = False
    elif k in ("line3d", "scatter3d"):
        P = np.column_stack([s.x, s.y, s.z]).astype(float)
        idx = rdp(P, RDP_TOL_MM) if k == "line3d" and len(P) > MAX_POINTS else np.arange(len(P))
        _write_dat(out / name, {"x": P[idx, 0], "y": P[idx, 1], "z": P[idx, 2]})
        mode = "no markers" if k == "line3d" else f"only marks, jtsmm/mark/{_role_key(s.role)}"
        lines.append(f"\\addplot3[{_opts(s, mode)}] table[x=x, y=y, z=z] {{{rel}/{name}}};")
    elif k == "surface3d":
        z = np.asarray(s.z, float)
        X, Y = np.meshgrid(np.asarray(s.x, float), np.asarray(s.y, float))
        C = np.asarray(s.c if s.c is not None else z, float)
        _write_dat(out / name, {"x": X.ravel(), "y": Y.ravel(), "z": z.ravel(),
                                "c": C.ravel()})
        cmap = "jtdiv" if s.style.get("ramp") == "diverging" else "jtseq"
        lines.append(f"\\addplot3[surf, shader=faceted interp, mesh/rows={z.shape[0]}, "
                     f"mesh/cols={z.shape[1]}, point meta=explicit, colormap name={cmap}, "
                     f"opacity={float(s.style.get('alpha', 1.0)):g}] "
                     f"table[x=x, y=y, z=z, meta=c] {{{rel}/{name}}};")
        legend = False
    elif k == "arrow3d":
        d = np.asarray(s.d, float).reshape(-1, 3)
        _write_dat(out / name, {"x": np.atleast_1d(s.x), "y": np.atleast_1d(s.y),
                                "z": np.atleast_1d(s.z), "u": d[:, 0], "v": d[:, 1],
                                "w": d[:, 2]})
        lines.append(f"\\addplot3[{_opts(s)}, -stealth, no markers, quiver={{u=\\thisrow{{u}},"
                     f" v=\\thisrow{{v}}, w=\\thisrow{{w}}}}] table[x=x, y=y, z=z]"
                     f" {{{rel}/{name}}};")
    if legend == "added":                     # the entry was placed by the branch itself
        return lines, bool(lines)
    if legend and lines:
        lines.append(f"\\addlegendentry{{{_esc(s.label)}}}")
    return lines, legend and bool(lines)


def _ticks(ax: str, a: L.AxisLayout) -> list[str]:
    o = [f"{ax}tick={{{','.join(_fmt(t) for t in a.ticks)}}}",
         f"{ax}ticklabels={{{','.join('{' + _esc(t) + '}' for t in a.labels)}}}"]
    if a.rotate:
        o.append(f"{ax}ticklabel style={{rotate={a.rotate}, anchor=east}}")
    return o


def _axis_opts(pl: L.PanelLayout, legend_name: str | None) -> str:
    p = pl.panel
    b = pl.axis
    is3d = p.projection == "3d"
    o = ["jtsmm/base3d" if is3d else "jtsmm/base", f"at={{({b.x0:.4f}in,{-b.y0:.4f}in)}}",
         "anchor=north west", f"width={b.w:.4f}in", f"height={b.h:.4f}in"]
    # 2-D axis labels are drawn as absolute nodes in the layout's label bands after the
    # axis (render_figure); empty label options would still create invisible nodes.
    if is3d:
        if p.x.label:
            o.append(f"xlabel={{{_axis_label(p.x.label, p.x.unit)}}}")
        if p.y.label:
            o.append(f"ylabel={{{_axis_label(p.y.label, p.y.unit)}}}")
    # Titles and panel tags are absolute nodes in the layout's bands (render_figure).
    for ax, a in (("x", pl.x), ("y", pl.y)):
        o += [f"{ax}min={_fmt(a.lim[0])}", f"{ax}max={_fmt(a.lim[1])}"]
        if a.log:
            o.append(f"{ax}mode=log")
        o += _ticks(ax, a)
    heat = any(s.kind == "heatmap" for s in p.series)
    if p.y.reverse or heat:
        o.append("y dir=reverse")
    if heat or any(s.kind == "image" for s in p.series):
        o.append("grid=none")
    if L.frameless(p):
        o += ["grid=none", "axis line style={draw=none}", "major tick length=0pt"]
    if is3d and pl.z is not None:
        o += [f"zmin={_fmt(pl.z.lim[0])}", f"zmax={_fmt(pl.z.lim[1])}",
              *([f"zlabel={{{_axis_label(p.z.label, p.z.unit)}}}"] if p.z.label else []),
              *_ticks("z", pl.z),
              f"view={{{p.view[0] + 90:.1f}}}{{{p.view[1]:.1f}}}", "unit vector ratio=1 1 1"]
    mode = pl.mode_legend
    if mode == "below" and legend_name:
        o += [f"legend to name={legend_name}", f"legend columns={max(pl.legend_cols, 1)}"]
    elif mode.startswith("inside:"):
        o.append(f"legend pos={mode[7:]}")
    elif p.legend_entries():
        # no legend for this panel (another panel's carries the entries): pgfplots draws
        # one at the top right for any \addlegendentry, so park it under a name never used
        o.append("legend to name=jtsmmnolegend")
    if p.colorbar is not None:
        cb = p.colorbar
        lim = cb.lim
        meta: list[str] = []
        if lim:
            lim = _meta_lim(lim, np.zeros(1))
            meta = [f"point meta min={_fmt(lim[0])}", f"point meta max={_fmt(lim[1])}"]
        elif cb.ramp == "diverging":
            # The colourbar takes the axis' meta range: symmetric about 0 like the cells
            # (each plot sets the same range via _meta_lim).
            vals = [np.ravel(np.asarray(s.z, float)) for s in p.series if s.kind == "heatmap"]
            vals += [np.ravel(np.asarray(s.c, float)) for s in p.series if s.c is not None]
            vals += [np.ravel(np.asarray(s.img, float)) for s in p.series
                     if s.kind == "image" and s.style.get("cmap")]
            if vals:
                lim = _meta_lim(None, np.concatenate(vals), diverging=True)
                meta = [f"point meta min={_fmt(lim[0])}", f"point meta max={_fmt(lim[1])}"]
        # Explicit tick labels in the text font with a real minus, as on the axes (pgfplots
        # would typeset its own numbers in the serif math font).
        ticks = list(cb.ticks) if cb.ticks else []
        dec = max((L._decimals(abs(b - a)) for a, b in zip(ticks, ticks[1:])), default=0) \
            if ticks else 0
        if not ticks and lim and np.isfinite(lim).all() and lim[1] > lim[0]:
            ticks, dec = L.linear_ticks(float(lim[0]), float(lim[1]), 5)
        tk = (f", ytick={{{','.join(_fmt(t) for t in ticks)}}},"
              f" yticklabels={{{','.join('{' + _esc(L.fmt_tick(t, dec)) + '}' for t in ticks)}}}"
              if ticks else "")
        o += ["colorbar right", f"colormap name={'jtseq' if cb.ramp == 'sequential' else 'jtdiv'}",
              f"colorbar style={{width=0.09in, ylabel style={{font={_FONT_CMD['label']}}},"
              f" ylabel={{{_axis_label(cb.label, cb.unit)}}},"
              f" tick label style={{font={_FONT_CMD['tick']}, text=jtink2}},"
              f" axis line style={{draw=none}}" + tk + "}"] + meta
    return ",\n  ".join(o)


def _baseline(top_in: float, pt: float, line: int = 0) -> float:
    """Baseline (in, from the top) of text line ``line`` in a band starting at ``top_in``
    whose lines are ``layout.line_height_in(pt)`` apart."""
    return top_in + L.line_height_in(pt) * line + 0.95 * pt / 72.0


def _heading_tex(pl: L.PanelLayout, F: dict[str, float]) -> list[str]:
    """Title lines and the bold panel tag, as absolute nodes on common baselines."""
    out = []
    if pl.title is not None and pl.title_lines:
        for i, t in enumerate(pl.title_lines):
            out.append(f"\\node[anchor=base west, inner sep=0pt, font={_FONT_CMD['title']},"
                       f" text=jtink] at ({pl.title.x0:.4f}in,"
                       f"{-_baseline(pl.title.y0, F['title'], i):.4f}in) {{{_esc(t)}}};")
    if pl.tag is not None and pl.tag_text:
        out.append(f"\\node[anchor=base west, inner sep=0pt, font={_FONT_CMD['tag']},"
                   f" text=jtink] at ({pl.tag.x0:.4f}in,{-_baseline(pl.tag.y0, F['tag']):.4f}in)"
                   f" {{{_esc(pl.tag_text)}}};")
    return out


def _prov_line(prov: dict | None) -> list[str]:
    if not prov:
        return []
    git = prov.get("git") or {}
    sha = (git.get("sha") or "")[:9] + ("+dirty" if git.get("dirty") else "")
    return [f"% Data: {prov.get('snapshot')} store, run {prov.get('newest_run')}; code {sha}; "
            f"exported {prov.get('exported_utc')}"]


def render_figure(spec: FigureSpec, out_dir: str | Path, *, data_root: str | Path | None = None,
                  lay: L.FigureLayout | None = None, prov: dict | None = None,
                  venue: str | style.Venue | None = None) -> Path:
    """``figures/<id>/fig.tex`` (+ data files) laid out for ``venue`` (default: the active
    one); the style file written by :func:`write_style` must be for the same venue."""
    out_dir = Path(out_dir)
    fdir = out_dir / "figures" / spec.id
    fdir.mkdir(parents=True, exist_ok=True)
    root = Path(data_root) if data_root else out_dir
    rel = fdir.relative_to(root).as_posix() if fdir.is_relative_to(root) else fdir.as_posix()
    lay = lay or L.compute(spec, venue=venue)
    lines = [f"% Generated by biomech.viz.render_pgf from spec '{spec.id}' -- do not edit.",
             f"% Sources: {', '.join(spec.sources)}", *_prov_line(prov),
             f"% Size: {lay.width:.2f} x {lay.height:.2f} in"
             + (f"; venue: {lay.venue}" if lay.venue else "")
             + (f"; perspective: {spec.perspective}" if spec.perspective else ""),
             "\\begin{tikzpicture}",
             "\\ifdefined\\jtsmmfigsetup\\jtsmmfigsetup\\fi",
             # Invisible frame: the picture's bounding box is exactly the layout. The size
             # test (standalone_figure) switches it off to measure the real content.
             f"\\ifdefined\\jtsmmnaturalbbox\\else\\path[use as bounding box] (0,0) rectangle"
             f" ({lay.width:.4f}in,{-lay.height:.4f}in);\\fi"]
    for pi, pl in enumerate(lay.panels):
        lname = f"lg{_role_key(spec.id)}p{pi}"
        body: list[str] = []
        has_legend = False
        for si, s in enumerate(pl.panel.series):
            tex, leg = _series_tex(s, pl, pi, si, fdir, rel)
            body += tex
            has_legend |= leg
        env = "axis"
        lines.append(f"\\begin{{{env}}}[\n  {_axis_opts(pl, lname if has_legend else None)}]")
        lines += body
        if pl.panel.note:
            lines.append(f"\\node[anchor=north west, inner sep=2pt, font={_FONT_CMD['note']},"
                         f" text=jtink2] at (rel axis cs:0,1) {{{_esc(pl.panel.note)}}};")
        lines.append(f"\\end{{{env}}}")
        lines += _heading_tex(pl, lay.font)
        p = pl.panel
        if p.projection != "3d":
            if p.x.label and pl.xlabel_band is not None:
                xb = pl.xlabel_band
                lines.append(f"\\node[anchor=north, inner sep=0pt, font={_FONT_CMD['label']},"
                             f" text=jtink] at ({xb.x0 + xb.w / 2:.4f}in,{-xb.y0:.4f}in)"
                             f" {{{_axis_label(p.x.label, p.x.unit)}}};")
            if p.y.label and pl.ylabel_band is not None:
                yb = pl.ylabel_band
                lines.append(f"\\node[anchor=north, rotate=90, inner sep=0pt,"
                             f" font={_FONT_CMD['label']}, text=jtink] at ({yb.x0:.4f}in,"
                             f"{-(yb.y0 + yb.h / 2):.4f}in) {{{_axis_label(p.y.label, p.y.unit)}}};")
        if has_legend and pl.mode_legend == "below" and pl.legend is not None:
            lb = pl.legend
            lines.append(f"\\node[anchor=north west, inner sep=0pt] at ({lb.x0:.4f}in,"
                         f"{-lb.y0:.4f}in) {{\\pgfplotslegendfromname{{{lname}}}}};")
    lines.append("\\end{tikzpicture}")
    path = fdir / "fig.tex"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


# -- tables ----------------------------------------------------------------------------------
def _cell(v: Any, c: Column) -> str:
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "{--}" if c.align == "S" else "--"
    if isinstance(v, (int, float, np.floating, np.integer)) and c.align == "S":
        return f"{float(v):.{c.decimals}f}"
    return _esc(str(v)) if c.align != "S" else f"{{{_esc(str(v))}}}"


def _header_chars(width: str, n_cols: int) -> int:
    """Characters a column header may take per line: the table width shared by the columns
    (about 4.4 pt per character at table size; at least 8)."""
    pts = 252.0 if width == "\\columnwidth" else 516.0
    return max(8, int(pts / 4.4 / max(n_cols, 1)) - 1)


def _wrap_header(text: str, unit: str, max_chars: int | None) -> str:
    """A column header that never forces the table wider than the page: long headers break
    into lines (``\\shortstack``), the unit on its own line when it does not fit; wrapping
    (X) columns are left to tabularx."""
    import textwrap

    # per-mode=symbol as in the figures ("mm/s²", not "mm s⁻²")
    u = f"(\\si[per-mode=symbol]{{{unit}}})" if unit else ""
    # Inline math ($...$) is a few glyphs wide and must never be split across lines.
    visible = re.sub(r"\$[^$]*\$", "xx", text)
    if max_chars is None or len(visible) + (len(unit) + 3 if unit else 0) <= max_chars \
            or "$" in text:
        return _esc(text) + (f" {u}" if u else "")
    # a word longer than the line stays whole (a cut "Participan|t" reads worse than a
    # slightly wider column)
    lines = [_esc(x) for x in textwrap.wrap(text, max_chars, break_on_hyphens=False,
                                            break_long_words=False)] or [""]
    if u:
        if len(lines[-1]) + len(unit) + 3 <= max_chars:
            lines[-1] += f" {u}"
        else:
            lines.append(u)
    return "\\shortstack{" + "\\\\".join(lines) + "}"


def render_table(spec: TableSpec, out_dir: str | Path, prov: dict | None = None) -> Path:
    out = Path(out_dir) / "tables"
    out.mkdir(parents=True, exist_ok=True)

    def colspec(c: Column) -> str:
        if c.align == "S":
            whole = 3
            vals = [abs(float(r[c.key])) for r in spec.rows if isinstance(r.get(c.key), (int, float))
                    and np.isfinite(r[c.key])]
            if vals:
                whole = max(1, len(str(int(max(vals)))))
            neg = "-" if any(isinstance(r.get(c.key), (int, float)) and r[c.key] < 0
                             for r in spec.rows) else ""
            return f"S[table-format={neg}{whole}.{c.decimals}]"
        if c.align == "X":                 # wrapping text: shares the free width
            return ">{\\raggedright\\arraybackslash}X"
        return c.align

    width = "\\columnwidth" if spec.width == "column" else "\\textwidth"
    # Wrapping columns need tabularx (X columns share the width left by the others);
    # otherwise tabular* spreads the slack between the columns.
    wrap = any(c.align == "X" for c in spec.columns)
    head = []
    per_col = _header_chars(width, len(spec.columns))
    for c in spec.columns:
        h = _wrap_header(c.header, c.unit, None if c.align == "X" else per_col)
        head.append(f"{{{h}}}" if c.align == "S" else h)
    lines = [f"% Generated by biomech.viz.render_pgf from table spec '{spec.id}' -- do not edit.",
             f"% Sources: {', '.join(spec.sources)}", *_prov_line(prov),
             (f"\\begin{{tabularx}}{{{width}}}{{@{{}}"
              f"{''.join(colspec(c) for c in spec.columns)}@{{}}}}" if wrap else
              f"\\begin{{tabular*}}{{{width}}}{{@{{\\extracolsep{{\\fill}}}}"
              f"{''.join(colspec(c) for c in spec.columns)}@{{}}}}"),
             "\\toprule"]
    groups = [c.group for c in spec.columns]
    if any(groups):
        cells, rules, i = [], [], 0
        while i < len(groups):
            j = i
            while j + 1 < len(groups) and groups[j + 1] == groups[i]:
                j += 1
            n = j - i + 1
            cells.append(f"\\multicolumn{{{n}}}{{c}}{{{_esc(groups[i] or '')}}}")
            if groups[i]:
                rules.append(f"\\cmidrule(lr){{{i + 1}-{j + 1}}}")
            i = j + 1
        lines.append(" & ".join(cells) + " \\\\")
        if rules:
            lines.append(" ".join(rules))
    lines.append(" & ".join(head) + " \\\\")
    lines.append("\\midrule")
    for r in spec.rows:
        if r.get("_rule"):
            lines.append("\\midrule")
            continue
        if r.get("_head"):                 # a group heading: one italic line across the table
            text = _esc(str(r.get(spec.columns[0].key, "") or ""))
            lines.append(f"\\multicolumn{{{len(spec.columns)}}}{{@{{}}l}}"
                         f"{{\\textit{{{text}}}}} \\\\")
            continue
        lines.append(" & ".join(_cell(r.get(c.key), c) for c in spec.columns) + " \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabularx}" if wrap else "\\end{tabular*}")
    if spec.notes:
        lines.append("\\par\\vspace{2pt}{\\footnotesize\\raggedright\\textit{Note.} "
                     f"{_esc(spec.notes)}\\par}}")
    path = out / f"{spec.id}.tex"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


PREAMBLE = ("\\usepackage{amssymb}\\usepackage{pgfplots}\\pgfplotsset{compat=1.18}\n"

            "\\usepackage{booktabs}\\usepackage{siunitx}\\usepackage{array}\\usepackage{tabularx}\n"
            "\\input{jtsmm-pgfstyle}\n")


def _venue_fonts(V: style.Venue) -> str:
    """The venue's figure typeface for documents without a paper around them (preview,
    standalone figures): Times-like for IEEE, Helvetica-like sans for Springer / Nature.
    Only under LuaLaTeX (fontspec); pdfLaTeX keeps Computer Modern."""
    return ("\\ifdefined\\directlua\n" + V.upload_fonts + "\\fi\n") if V.upload_fonts else ""


def _source_note(item_id: str, sources: str = "", prov: dict | None = None) -> str:
    """The small line under a caption: item id, sources and the data provenance."""
    parts = [f"\\texttt{{{_esc(item_id)}}}"]
    if sources:
        parts.append(f"Sources: {sources}")
    if prov:
        git = prov.get("git") or {}
        sha = (git.get("sha") or "")[:9] + ("+dirty" if git.get("dirty") else "")
        # the snapshot name identifies the store; the variant name is not printed (it is an
        # internal folder name and differs in the public release, 2026-11-15)
        store = str(prov.get("snapshot") or "live")
        parts.append(f"Data: {_esc(store)}, code {_esc(sha)}")
    return ("\\par\\vspace{2pt}{\\scriptsize\\raggedright "
            + " \\textperiodcentered{} ".join(parts) + "\\par}")


def standalone_preview(out_dir: str | Path, items: list[tuple[str, str]], name: str = "preview",
                       venue: str | style.Venue | None = None,
                       captions: dict[str, tuple[str, str]] | None = None,
                       prov: dict | None = None) -> Path:
    """A compilable document of the venue's page geometry showing exported figures/tables
    (``items``: ("figure"|"table", id)), each with its caption (``captions``: id ->
    (caption, sources), both LaTeX-escaped; J1.1) and a line with the id, sources and
    provenance. Compile it in ``out_dir`` (LuaLaTeX recommended)."""
    V = style.venue(venue)
    out_dir = Path(out_dir)
    captions = captions or {}
    body = []
    for kind, i in items:
        cap, src = captions.get(i, ("", ""))
        cap = cap or _esc(i)
        note = _source_note(i, src, prov)
        if kind == "figure":
            body.append(f"\\begin{{figure*}}[p]\\centering\\input{{figures/{i}/fig.tex}}"
                        f"\\caption[{_esc(i)}]{{{cap}}}{note}\\end{{figure*}}")
        else:
            body.append(f"\\begin{{table*}}[p]\\centering\\footnotesize"
                        f"\\caption[{_esc(i)}]{{{cap}}}"
                        f"\\input{{tables/{i}.tex}}{note}\\end{{table*}}")
        body.append("\\clearpage")
    if V.name in ("ieee", "ieee8"):
        # The RAS ieeeconf.cls (PaperPlaza template) is not in TeX Live; article in two
        # columns with this geometry reproduces its 3.5-in column and 7.16-in text width.
        geom = ("\\documentclass[10pt,twocolumn,letterpaper]{article}\n"
                "\\usepackage[top=0.75in,bottom=1in,left=0.62in,right=0.62in,columnsep=0.24in]"
                "{geometry}\n")
    else:
        sep = max(V.text_in - 2 * V.column_in, 0.0)
        geom = ("\\documentclass[10pt,twocolumn,a4paper]{article}\n"
                f"\\usepackage[textwidth={V.text_in:.4f}in,columnsep={sep:.4f}in,"
                "top=0.9in,bottom=1in,hcentering]{geometry}\n")
    doc = (geom + _venue_fonts(V) + PREAMBLE +
           "\\begin{document}\n" + "\n".join(body) + "\n\\end{document}\n")
    p = out_dir / f"{name}.tex"
    p.write_text(doc, encoding="utf-8")
    return p


def captioned_item(out_dir: str | Path, kind: str, item_id: str, caption: str,
                   sources: str = "", prov: dict | None = None,
                   venue: str | style.Venue | None = None, width: str = "column",
                   label: str | None = None) -> Path:
    """One figure or table with its caption, sources and provenance, cropped to the venue's
    column or text width (J1.1): the self-contained PDF for review and co-authors
    (``captioned/<id>.pdf``; the journal-upload PDF stays caption-free). ``caption`` and
    ``sources`` are LaTeX-escaped. Writes ``captioned_<id>.tex`` in ``out_dir`` (compile it
    there)."""
    V = style.venue(venue)
    out_dir = Path(out_dir)
    w = V.width_in(width)
    what = "Figure" if kind == "figure" else "Table"
    head = f"\\textbf{{{what}}}" + (f" ({_esc(label)})" if label else "") + ". "
    content = (f"\\input{{figures/{item_id}/fig.tex}}" if kind == "figure"
               else f"{{\\footnotesize\\input{{tables/{item_id}.tex}}}}")
    capbox = f"{{\\small\\raggedright {head}{caption}\\par}}"
    inner = ([content, "\\par\\vspace{6pt}", capbox] if kind == "figure"
             else [capbox, "\\par\\vspace{4pt}", content])
    doc = ("\\documentclass[10pt,border=6pt]{standalone}\n" + _venue_fonts(V) + PREAMBLE +
           "\\begin{document}\n"
           f"\\begin{{minipage}}{{{w:.4f}in}}\\centering\n" + "\n".join(inner) + "\n"
           + _source_note(item_id, sources, prov) + "\n\\end{minipage}\n\\end{document}\n")
    p = out_dir / f"captioned_{item_id}.tex"
    p.write_text(doc, encoding="utf-8")
    return p


# LuaTeX hook of the size test: the smallest font size of any glyph on the
# shipped page, written to the log as "JTSMM-MINFONT <pt>".
MINFONT_LUA = """\
local minsize = nil
local GLYPH = node.id("glyph")
local function walk(head)
  for n in node.traverse(head) do
    if n.id == GLYPH then
      local f = font.getfont(n.font)
      if f and f.size and (minsize == nil or f.size < minsize) then minsize = f.size end
    elseif n.list then
      walk(n.list)
    end
  end
end
luatexbase.add_to_callback("pre_shipout_filter", function(box)
  walk(box)
  if minsize then texio.write_nl(string.format("JTSMM-MINFONT %.2f", minsize / 65536)) end
  return true
end, "jtsmm_minfont")
"""


def standalone_figure(out_dir: str | Path, fig_id: str, venue: str | style.Venue | None = None,
                      *, natural: bool = True, name: str | None = None) -> Path:
    """One figure in a ``standalone`` document, in the venue's typeface.

    ``natural`` (the size test): cropped to the real content, so text that runs past the
    layout shows up as extra width. Otherwise (the journal upload, ``export --standalone``)
    the page is exactly the layout box -- the venue's column or text width."""
    V = style.venue(venue)
    out_dir = Path(out_dir)
    probe = ""
    if natural:                     # the size test also logs the smallest glyph size
        (out_dir / "jtsmm-minfont.lua").write_text(MINFONT_LUA, encoding="utf-8")
        probe = "\\directlua{dofile('jtsmm-minfont.lua')}\n"
    doc = ("\\documentclass[10pt]{standalone}\n" + ("\\def\\jtsmmnaturalbbox{}\n" if natural else "")
           + _venue_fonts(V) + PREAMBLE + probe +
           f"\\begin{{document}}\\input{{figures/{fig_id}/fig.tex}}\\end{{document}}\n")
    p = out_dir / f"{name or ('standalone_' + fig_id)}.tex"
    p.write_text(doc, encoding="utf-8")
    return p
